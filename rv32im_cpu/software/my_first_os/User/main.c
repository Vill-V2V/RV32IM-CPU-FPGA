int main(void) {
    // 1. 初始化测试寄存器 x5 和 x6
    // 用汇编强行将数据写入特定寄存器，方便我们在波形中抓取
    __asm__ volatile("li x5, 2");  // 寄存器 x5 = 2
    __asm__ volatile("li x6, 3");  // 寄存器 x6 = 3

    // -----------------------------------------------------------
    // ? 测试项 1：Zba 扩展 -> sh1add x7, x5, x6
    // 逻辑：x7 = (x5 << 1) + x6 = (2 * 2) + 3 = 7
    // 机器码解析：0x2062A3B3 
    // -----------------------------------------------------------
    __asm__ volatile(".word 0x2062A3B3"); 

    // -----------------------------------------------------------
    // ? 测试项 2：Zbb 扩展 -> max x8, x5, x6
    // 逻辑：x8 = max(x5, x6) = max(2, 3) = 3
    // 机器码解析：0x0A62E433
    // -----------------------------------------------------------
    __asm__ volatile(".word 0x0A62E433"); 

    // -----------------------------------------------------------
    // ? 测试项 3：Zbs 扩展 -> bset x9, x5, x6
    // 逻辑：x9 = x5 | (1 << x6) = 2 | (1 << 3) = 2 | 8 = 10
    // 机器码解析：0x286294B3
    // -----------------------------------------------------------
    __asm__ volatile(".word 0x286294B3"); 

    // 测试完毕，进入死循环，保持波形稳定
    while (1) {
        __asm__ volatile("nop");
    }

    return 0;
}